import fs from "node:fs";
import path from "node:path";
import { stripTypeScriptTypes } from "node:module";

const originalEmitWarning = process.emitWarning;
process.emitWarning = () => {};

const repoRoot = process.cwd();
const appRoot = path.join(repoRoot, "apps", "extension");
const distRoot = path.join(appRoot, "dist");
const sourceRoot = path.join(appRoot, "src");
const driverRoot = path.join(repoRoot, "packages", "driver", "src");
const coreRoot = path.join(repoRoot, "packages", "core", "src");

assertInside(repoRoot, distRoot);
prepareDistRoot();

copyFile(path.join(appRoot, "panel.html"), path.join(distRoot, "panel.html"));
copyTree(sourceRoot, path.join(distRoot, "src"));

const distDriverRoot = path.join(distRoot, "src", "vendor", "newton-browser-driver");
for (const file of ["controller.js", "chrome-tabs-port.js"]) {
  copyFile(path.join(driverRoot, file), path.join(distDriverRoot, file));
}
const driverSource = fs.readFileSync(path.join(driverRoot, "driver.js"), "utf8")
  .replaceAll("\"src/overlay.css\"", "\"dist/src/overlay.css\"")
  .replaceAll("\"src/overlay.js\"", "\"dist/src/overlay.js\"");
writeFile(path.join(distDriverRoot, "driver.js"), driverSource);
copyFile(path.join(driverRoot, "overlay.js"), path.join(distRoot, "src", "overlay.js"));
copyFile(path.join(driverRoot, "overlay.css"), path.join(distRoot, "src", "overlay.css"));

const distCoreRoot = path.join(distRoot, "src", "vendor", "newton-browser-core");
for (const file of ["protocol.ts", "transport.ts", "action-schema.ts", "text-redaction.ts", "redaction.ts", "host-policy.ts", "risk.ts"]) {
  const source = fs.readFileSync(path.join(coreRoot, file), "utf8");
  const transformed = stripTypeScriptTypes(source, { mode: "transform" })
    .replaceAll(".ts\";", ".js\";")
    .replaceAll(".ts\"", ".js\"")
    .replaceAll(".ts'", ".js'");
  const outputName = file.replace(/\.ts$/, ".js");
  writeFile(path.join(distCoreRoot, outputName), `${transformed.trimEnd()}\n`);
}

writeFile(path.join(distRoot, "BUILD_INFO.txt"), [
  "Generated by scripts/build-extension.mjs.",
  "Do not edit this folder. Source lives in apps/extension and packages/core + packages/driver.",
  "Load the unpacked extension from apps/extension, not this generated dist folder.",
  "",
].join("\n"));

console.log(`newton browser extension build ok: ${path.relative(repoRoot, distRoot).replaceAll("\\", "/")}`);
process.emitWarning = originalEmitWarning;

function prepareDistRoot() {
  try {
    fs.rmSync(distRoot, { recursive: true, force: true, maxRetries: 5, retryDelay: 50 });
  } catch (error) {
    if (!["EPERM", "ENOTEMPTY", "EBUSY"].includes(error?.code)) throw error;
    // Chromium can keep the unpacked extension's generated files open while it
    // is loaded. In that case, overwrite the generated tree in place; a browser
    // reload will pick up the new bytes.
  }
  fs.mkdirSync(distRoot, { recursive: true });
}
function copyTree(from, to) {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.name === "vendor") continue;
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) {
      copyTree(source, target);
      continue;
    }
    copyFile(source, target);
  }
}

function copyFile(from, to) {
  writeFile(to, fs.readFileSync(from));
}

function writeFile(file, content) {
  assertInside(distRoot, file);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function assertInside(parent, child) {
  const relative = path.relative(parent, child);
  if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new Error(`Refusing to write outside ${parent}: ${child}`);
  }
}
